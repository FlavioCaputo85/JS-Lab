function hl(s) {
  return s
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(
      /(\/\/.*)|("[^"\n]*"|`[^`]*`|'[^'\n]*')|\b(const|let|var|function|return|if|else|for|while|of|new|await|async)\b|\b(\d+)\b/g,
      (m, c, s2, k, n) =>
        c
          ? `<span class="c">${c}</span>`
          : s2
            ? `<span class="s">${s2}</span>`
            : k
              ? `<span class="k">${k}</span>`
              : `<span class="n">${n}</span>`,
    );
}

